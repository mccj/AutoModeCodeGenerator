using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

using AutoModeCodeGenerator.Internal;

/// <summary>
/// 双主入口 A：基于特性的增量源生成器。扫描带 <c>AutoCodeCrudModes</c> / <c>AutoCodeClassModes</c> 的接口或类，
/// 经 Extract → Expand → Emit 生成多产物类型（与 <see cref="AutoFilesGenerator"/> 共享 Emit）。
/// 管线说明见仓库 <c>docs/ARCHITECTURE.md</c>。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class AutoCodeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 注入公共 API（AutoCode* 特性、常量、Inpc 基类）到消费方编译。
        context.RegisterPostInitializationOutput(static ctx =>
        {
            var source = SourceGeneratorHelper.AutoGenerated + EmbeddedTemplates.ReadAutoCodeAttributes();
            ctx.AddSource("AutoCodeAttribute.g.cs", SourceText.From(source, Encoding.UTF8));
        });

        var options = context.AnalyzerConfigOptionsProvider
            .Select(static (provider, _) => AutoModeGeneratorOptions.From(provider.GlobalOptions));

        var models = context.SyntaxProvider.CreateSyntaxProvider(
                static (syntaxNode, _) =>
                    syntaxNode.IsKind(SyntaxKind.ClassDeclaration)
                    || syntaxNode.IsKind(SyntaxKind.InterfaceDeclaration),
                static (ctx, cancellationToken) =>
                {
                    if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, cancellationToken) is not INamedTypeSymbol symbol)
                        return null;

                    if (!GenerationModelExtractor.HasGenerationAttributes(symbol))
                        return null;

                    return new ExtractInput(symbol, ctx.Node.GetLocation());
                })
            .Where(static input => input is not null)
            .Combine(options)
            .Select(static (pair, cancellationToken) =>
            {
                var (input, opts) = pair;
                return GenerationModelExtractor.Extract(input!.Symbol, input.Location, opts, cancellationToken);
            })
            .WithTrackingName("AutoCode.ExtractModel");

        context.RegisterSourceOutput(models, static (ctx, model) =>
        {
            foreach (var diagnostic in model.Diagnostics)
                ctx.ReportDiagnostic(diagnostic);

            if (model.ClassInfos.IsDefaultOrEmpty)
                return;

            var sourceCode = SourceGeneratorHelper.GeneratorCode(model.Nullable, model.ClassInfos);
            ctx.AddSource($"{model.FileName}.g.cs", SourceText.From(sourceCode, Encoding.UTF8));
        });
    }

    private sealed record ExtractInput(INamedTypeSymbol Symbol, Location Location);
}

using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

using 自动代码生成;

/// <summary>
/// 基于特性的增量源生成器：扫描带 <c>AutoCodeClassModes</c> 的接口或类，在编译期生成实现代码。
/// </summary>
[Generator(LanguageNames.CSharp)]
public partial class AutoCodeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 注册嵌入的特性定义模板，供消费项目编译使用。
        context.RegisterPostInitializationOutput(static ctx =>
        {
            var source = SourceGeneratorHelper.AutoGenerated + EmbeddedTemplates.ReadAutoCodeAttributes();
            ctx.AddSource("AutoCodeAttribute.g.cs", SourceText.From(source, Encoding.UTF8));
        });

        // 仅处理带 AutoCodeClassModes 的类或接口声明。
        var typeContexts = context.SyntaxProvider.ForAttributeWithMetadataName(
            GenerationModelExtractor.AutoCodeClassModesAttribute,
            static (SyntaxNode syntaxNode, CancellationToken cancellationToken) =>
                syntaxNode.IsKind(SyntaxKind.ClassDeclaration) || syntaxNode.IsKind(SyntaxKind.InterfaceDeclaration),
            static (GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken) =>
                ((INamedTypeSymbol)context.TargetSymbol, context.TargetNode.GetLocation()));

        var models = typeContexts
            .Select(static (input, cancellationToken) =>
                GenerationModelExtractor.Extract(input.Item1, input.Item2, cancellationToken))
            .WithTrackingName("AutoCode.ExtractModel");

        context.RegisterSourceOutput(models, static (ctx, model) =>
        {
            foreach (var diagnostic in model.Diagnostics)
                ctx.ReportDiagnostic(diagnostic);

            if (model.ClassInfos.IsDefaultOrEmpty)
                return;

            var sourceCode = SourceGeneratorHelper.GeneratorCode(model.Nullable, model.ClassInfos);
            ctx.AddSource($"{model.FileName}.g.cs", SourceText.From(sourceCode, Encoding.UTF8));
        });
    }
}

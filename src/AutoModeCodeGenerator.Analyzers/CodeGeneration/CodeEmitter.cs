using System.Collections.Immutable;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace 自动代码生成.CodeGeneration;

internal static class CodeEmitter
{
    private static readonly IClassStyleEmitter[] StyleEmitters =
    {
        new PocoClassEmitter(),
        new RecordClassEmitter(),
        new InpcClassEmitter(),
    };

    public static string Emit(NullableEnum? nullable, ImmutableArray<SourceGeneratorClassInfo> classInfos)
    {
        var builder = new StringBuilder(SourceGeneratorHelper.AutoGenerated);
        AppendNullableDirective(builder, nullable);

        var compilationUnit = CreateCompilationUnit(classInfos);
        builder.Append(SyntaxGenerationHelpers.FormatCompilationUnit(compilationUnit));
        return builder.ToString();
    }

    private static CompilationUnitSyntax CreateCompilationUnit(ImmutableArray<SourceGeneratorClassInfo> classInfos)
    {
        var usings = classInfos
            .SelectMany(classInfo => classInfo.Usings)
            .Distinct()
            .OrderBy(name => name)
            .Select(name => SyntaxFactory.UsingDirective(SyntaxFactory.ParseName(name)))
            .ToArray();

        var members = new List<MemberDeclarationSyntax>();
        foreach (var namespaceGroup in classInfos.GroupBy(classInfo => classInfo.ClassNamespace ?? string.Empty).OrderBy(group => group.Key))
        {
            var classDeclarations = namespaceGroup
                .Select(classInfo => GetEmitter(classInfo.ClassStyle).CreateClassDeclaration(classInfo))
                .Cast<MemberDeclarationSyntax>()
                .ToArray();

            if (string.IsNullOrWhiteSpace(namespaceGroup.Key))
            {
                members.AddRange(classDeclarations);
                continue;
            }

            members.Add(SyntaxFactory.NamespaceDeclaration(SyntaxFactory.ParseName(namespaceGroup.Key))
                .WithMembers(SyntaxFactory.List(classDeclarations)));
        }

        return SyntaxFactory.CompilationUnit()
            .WithUsings(SyntaxFactory.List(usings))
            .WithMembers(SyntaxFactory.List(members));
    }

    private static void AppendNullableDirective(StringBuilder builder, NullableEnum? nullable)
    {
        if (!nullable.HasValue)
            return;

        builder.AppendLine("#nullable " + nullable.Value switch
        {
            NullableEnum.Enable => "enable",
            NullableEnum.Disable => "disable",
            NullableEnum.Restore => "restore",
            NullableEnum.EnableWarnings => "enable warnings",
            NullableEnum.DisableWarnings => "disable warnings",
            NullableEnum.RestoreWarnings => "restore warnings",
            NullableEnum.EnableAnnotations => "enable annotations",
            NullableEnum.DisableAnnotations => "disable annotations",
            NullableEnum.RestoreAnnotations => "restore annotations",
            _ => throw new NotImplementedException(),
        });
    }

    private static IClassStyleEmitter GetEmitter(ClassStyleEnum style)
        => StyleEmitters.First(emitter => emitter.Style == style);
}
